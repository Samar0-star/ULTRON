    def on_progress(self, data: Dict[str, Any]):
        """Callback from DeepResearchOrchestrator._emit_progress."""
        phase = data.get("phase", "")
        msg = data.get("message", "")
        payload = data.get("payload", {})
        plan_data = data.get("plan") or (payload.get("plan") if isinstance(payload, dict) else None)

        if phase == "plan_created" or plan_data:
            self.set_active_stage(2, "STRATEGIC_PLANNING", "PlanCreator")
            tasks = plan_data.get("tasks", []) if isinstance(plan_data, dict) else []
            for t in tasks:
                if isinstance(t, dict):
                    self.record_plan_task(
                        task_id=str(t.get("id", f"TASK-{len(self.state.plan_tasks)+1:02d}")),
                        title=str(t.get("description", t.get("name", "Research task workstream"))),
                        assigned_agent=str(t.get("assigned_agent", t.get("agent_name", "SpecialistResearcher"))),
                        dependencies=",".join([str(d) for d in t.get("dependencies", [])]) or "None",
                        status="QUEUED",
                        feasibility="APPROVED"
                    )
            if msg:
                self.set_thinking(msg, "STRATEGIC_PLANNING", "PlanCreator")
            return

        if phase == "task_start" and isinstance(payload, dict):
            wid = payload.get("worker_id", "Agent-Worker")
            tid = payload.get("task_id", "task")
            desc = payload.get("description", payload.get("requirements", f"Task {tid}"))
            self.set_active_stage(4, "SWARM_EXPERIMENTATION", "ExperimentAgent")
            self.register_agent_spawn(wid, tid, desc)
        elif phase == "task_complete" and isinstance(payload, dict):
            wid = payload.get("worker_id", "Agent-Worker")
            res = payload.get("result", {})
            preview = res.get("summary", str(res)) if isinstance(res, dict) else str(res)
            self.update_agent_status(wid, "COMPLETED", preview)
            
            if isinstance(res, dict):
                initial_hash = res.get("initial_hash")
                if initial_hash:
                    final_hash = res.get("final_hash")
                    p_val = res.get("p_value") or res.get("p") or res.get("p-value")
                    cohens_d = res.get("cohens_d") or res.get("effect_size") or res.get("d")
                    ci_str = str(res.get("ci_95", res.get("ci", "[N/A]")))
                    
                    if p_val is not None:
                        try:
                            p_val = float(p_val)
                        except:
                            p_val = None
                    if cohens_d is not None:
                        try:
                            cohens_d = float(cohens_d)
                        except:
                            cohens_d = None
                            
                    hyp_ids = list(self.state.hypotheses.keys())
                    hyp_id = (
                        res.get("hypothesis_id")
                        or (res.get("metadata", {}).get("hypothesis_id") if isinstance(res.get("metadata"), dict) else None)
                        or payload.get("hypothesis_id")
                        or (hyp_ids[-1] if hyp_ids else "H-UNKNOWN")
                    )
                    tid = payload.get("task_id", "")
                    
                    self.record_experiment(
                        exp_id=f"EXP-{tid[-4:]}" if len(tid) >= 4 else f"EXP-{tid}",
                        hyp_id=hyp_id,
                        dataset=res.get("dataset_name", "Local Data"),
                        shape=res.get("dataset_shape", "Verified"),
                        ast_check=res.get("ast_check", "PASS"),
                        initial_hash=initial_hash,
                        final_hash=final_hash,
                        p_val=p_val,
                        cohens_d=cohens_d,
                        ci=ci_str,
                        status="STATS_COMPUTED" if p_val is not None else "POW_VERIFIED"
                    )
        elif phase == "task_fail" and isinstance(payload, dict):
            wid = payload.get("worker_id", "Agent-Worker")
            err = payload.get("error", "Error")
            self.update_agent_status(wid, "FAILED", str(err))
        elif phase in ["hypothesis_generation", "hypothesis_formulation"]:
            self.set_active_stage(3, "HYPOTHESIS_FORMATION", "HypothesisGenerator")
            if msg:
                self.set_thinking(msg, "HYPOTHESIS_FORMATION", "HypothesisGenerator")
        elif phase == "gnn_dream":
            self.set_active_stage(5, "GNN_TRIBUNAL_AUDIT", "GNNOracle")
            if msg:
                self.set_thinking(msg, "GNN_TRIBUNAL_AUDIT", "GNNOracle")
        elif phase in ["tribunal", "consensus"]:
            self.set_active_stage(5, "GNN_TRIBUNAL_AUDIT", "ConsensusTribunal")
            if msg:
                self.set_thinking(msg, "GNN_TRIBUNAL_AUDIT", "ConsensusTribunal")
        elif phase in ["epistemic", "cycle_synthesis"]:
            self.set_active_stage(6, "EPISTEMIC_SYNTHESIS", "EpistemicRegulator")
            if msg:
                self.set_thinking(msg, "EPISTEMIC_SYNTHESIS", "EpistemicRegulator")
        elif msg:
            self.set_thinking(msg, phase.upper() if phase else None)

    def on_log(self, record: logging.LogRecord):
        """Intercepts log messages to enrich dashboard state."""
        msg = record.getMessage()
        lvl = record.levelname
        
        if "urllib3" in msg or "DeprecationWarning" in msg:
            return

        ts = datetime.now().strftime("%H:%M:%S")
        self.state.recent_logs.append((ts, lvl, msg))

        if "[SURVIVOR TIER]" in msg:
            match = re.search(r'Promoted:.*?->\s*(\w+)', msg)
            if match:
                self.state.survivor_tier = match.group(1).upper()
        elif "[SEED]" in msg or "MASSIVE KNOWLEDGE HARVEST" in msg:
            self.set_thinking(msg.replace("[SEED]", "").strip(), "KNOWLEDGE_HARVEST", "LiteratureHarvester")
            match = re.search(r'committed (\d+) facts', msg)
            if match:
                self.state.facts_harvested += int(match.group(1))
        elif "[PLAN]" in msg or "create_plan" in msg:
            self.set_thinking(msg.replace("[PLAN]", "").strip(), "STRATEGIC_PLANNING", "PlanCreator")
        elif "Added hypothesis" in msg:
            # Added hypothesis H-123: Point mutations...
            match = re.search(r'Added hypothesis (.*?):\s*(.*)', msg)
            if match:
                self.record_hypothesis(
                    hyp_id=match.group(1).strip(),
                    statement=match.group(2).strip()[:100],
                    confidence=0.5,
                    status="IN_TESTING",
                    equation="SymPy Validation Pending"
                )
                self.set_active_stage(3, "HYPOTHESIS_FORMATION", "HypothesisGenerator")
        elif "[GENERATOR]" in msg or "[BRAINSTORM]" in msg:
            self.set_thinking(msg.replace("[GENERATOR]", "").replace("[BRAINSTORM]", "").strip(), "HYPOTHESIS_FORMATION", "HypothesisGenerator")
        elif "[RIGOR]" in msg or "Proof-of-Work" in msg:
            self.state.pow_verifications += 1
            self.set_thinking("Verifying cryptographic tensor weight divergent hash...", "POW_RIGOR_AUDIT", "ExperimentAgent")
        elif "Welch-Z" in msg:
            z_match = re.search(r'Welch-Z.*?([\d\.]+)', msg)
            z_val = float(z_match.group(1)) if z_match else None
            self.record_epistemic_event("WELCH_Z_AUDIT", "HypothesisPool", msg[:80], welch_z=z_val)
            self.set_active_stage(6, "EPISTEMIC_SYNTHESIS", "EpistemicRegulator")
        elif "GNN" in msg and "dream" in msg.lower():
            self.set_thinking("GNN Oracle dreaming across topological knowledge manifolds...", "GNN_DREAM", "GNNOracle")
            self.set_active_stage(5, "GNN_TRIBUNAL_AUDIT", "GNNOracle")
        elif "Training on active graph" in msg:
            match = re.search(r'\((\d+) nodes, (\d+) edges\)', msg)
            if match:
                self.update_gnn_oracle(nodes=int(match.group(1)), edges=int(match.group(2)))
        elif "[NUDITY]" in msg and "AUC:" in msg:
            match = re.search(r'AUC:\s*([\d\.]+)', msg)
            if match:
                self.update_gnn_oracle(nodes=self.state.gnn.active_nodes, edges=self.state.gnn.active_edges, auc=float(match.group(1)))
        elif "TRIBUNAL VERDICT:" in msg:
            match = re.search(r'VERDICT:\s*(\w+)\s*\((\d+)\s*approve,\s*(\d+)\s*reject,\s*(\d+)\s*abstain\)', msg)
            if match:
                verdict = match.group(1)
                approves = int(match.group(2))
                rejects = int(match.group(3))
                stat_vote = "APPROVED" if approves > 0 else ("REJECTED" if rejects > 0 else "PENDING")
                phys_vote = "APPROVED" if approves > 1 else ("REJECTED" if rejects > 1 else "PENDING")
                skeptic_vote = "APPROVED" if approves > 2 else ("REJECTED" if rejects > 2 else "PENDING")
                hyp_ids = list(self.state.hypotheses.keys())
                hyp_id = hyp_ids[-1] if hyp_ids else f"H-TRIB-{len(self.state.tribunal)+1}"
                self.update_tribunal(hyp_id, stat_vote, phys_vote, skeptic_vote, None, verdict)
                self.set_active_stage(5, "GNN_TRIBUNAL_AUDIT", "ConsensusTribunal")
        elif "Bayesian update:" in msg:
            # Bayesian update: H-123: 0.500  0.800
            match = re.search(r'Bayesian update:\s*(.*?):\s*([\d\.]+)\s*([\d\.]+)', msg)
            if match:
                hyp_id = match.group(1).strip()
                prior = float(match.group(2))
                posterior = float(match.group(3))
                slope = "positive" if posterior > prior else "negative"
                self.record_epistemic_event(
                    "LOGIT_UPDATE",
                    hyp_id,
                    f"Confidence slope {slope}; updated {prior:.2f} -> {posterior:.2f}.",
                    welch_z=None
                )
                if hyp_id in self.state.hypotheses:
                    self.state.hypotheses[hyp_id].confidence = posterior
                self.set_active_stage(6, "EPISTEMIC_SYNTHESIS", "EpistemicRegulator")
        elif "[MATH FIX]" in msg and "sympy strictly" in msg:
            hyp_ids = list(self.state.hypotheses.keys())
            if hyp_ids:
                self.record_epistemic_event(
                    "SYMPY_CHECK_PASS",
                    hyp_ids[-1],
                    "Validated dimensional bounds: Real Domain PASS",
                    welch_z=None
                )

        self.refresh()

