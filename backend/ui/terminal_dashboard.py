@dataclass
class PlanTaskRecord:
    """Tracks a decomposed strategic research task generated by PlanCreator."""
    task_id: str
    title: str
    assigned_agent: str
    dependencies: str = "None"
    status: str = "QUEUED"  # QUEUED, IN_PROGRESS, COMPLETED, FAILED
    feasibility: str = "APPROVED"


@dataclass
class AgentRecord:
    """Tracks a single worker in the swarm fleet."""
    agent_num: int
    worker_id: str
    role: str
    task_id: str
    task_desc: str
    status: str = "SPAWNING"  # SPAWNING, RUNNING, VERIFYING, COMPLETED, FAILED, HYDRA_RECOVERING
    start_time: float = field(default_factory=time.time)
    end_time: Optional[float] = None
    result_preview: Optional[str] = None
    pid: Optional[int] = None

    @property
    def duration_str(self) -> str:
        elapsed = (self.end_time or time.time()) - self.start_time
        mins, secs = divmod(int(elapsed), 60)
        return f"{mins:02d}:{secs:02d}"


@dataclass
class HypothesisRecord:
    """Tracks a formal hypothesis governed by the Epistemic Regulator."""
    id: str
    statement: str
    confidence: float
    status: str = "IN_TESTING"  # IN_TESTING, FALSIFICATION_SURVIVED, REFUTED, MUTATED, ARCHIVED
    welch_z: Optional[float] = None
    logit_slope: Optional[float] = None
    equation: Optional[str] = None
    evidence_count: int = 0
    falsification_metric: Optional[str] = None


@dataclass
class ExperimentRecord:
    """Tracks physical execution and cryptographic proof-of-work."""
    experiment_id: str
    hypothesis_id: str
    dataset_name: str
    dataset_shape: str = "(N/A)"
    ast_check: str = "PASS"
    pow_initial_hash: Optional[str] = None
    pow_final_hash: Optional[str] = None
    grad_norm: Optional[float] = None
    p_value: Optional[float] = None
    cohens_d: Optional[float] = None
    ci_95: Optional[str] = None
    status: str = "RUNNING"  # RUNNING, POW_VERIFIED, STATS_COMPUTED, FAILED


@dataclass
class GNNOracleRecord:
    """Tracks the Graph Neural Network intuition and dreaming layer."""
    active_nodes: int = 0
    active_edges: int = 0
    link_pred_auc: Optional[float] = None
    topological_entropy: Optional[float] = None
    dream_predictions: List[str] = field(default_factory=list)
    causal_interventions: List[str] = field(default_factory=list)


@dataclass
class TribunalRecord:
    """Tracks multi-agent consensus tribunal verdicts."""
    hypothesis_id: str
    statistician_vote: str = "PENDING"
    physicist_vote: str = "PENDING"
    skeptic_vote: str = "PENDING"
    noise_survival: Optional[float] = None
    verdict: str = "IN_REVIEW"


@dataclass
class EpistemicEventRecord:
    """Tracks an Epistemic Regulator action or event."""
    action_type: str
    target_id: str
    details: str
    welch_z: Optional[float] = None
    timestamp: str = field(default_factory=lambda: datetime.now().strftime("%H:%M:%S"))


class SVELDashboardState:
    """Unified scientific mission control state."""
    def __init__(self, mission_id: str, prompt: str, domain: str, mode: str, runtime_hours: float, max_parallel: int):
        self.mission_id = mission_id
        self.prompt = prompt
        self.domain = domain
        self.mode = mode
        self.runtime_hours = runtime_hours
        self.max_parallel = max_parallel
        self.start_time = time.time()
        self.current_cycle = 1
        self.max_cycles = 25
        
        # Phasic Lifecycle & Active Subsystem Tracking
        self.stage_index: int = 1  # 1: Seed, 2: Plan, 3: Hypothesis, 4: Swarm/Cleanroom, 5: GNN/Tribunal, 6: Epistemic
        self.current_stage: str = "KNOWLEDGE_SEED"
        self.active_agent: str = "LiteratureHarvester"
        self.current_phase = "INITIALIZING"
        self.current_thinking = "Booting sovereign cognitive runtime & verifying SQLite manifolds..."
        self.phase_start_time = time.time()
        self.thinking_stream: deque = deque(maxlen=4)

        # Strategic Plan Creator Tasks
        self.plan_tasks: List[PlanTaskRecord] = []

        # Discovery Mode Governance (from DiscoveryOrchestrator)
        self.survivor_tier: str = "ESCAPED"  # ESCAPED, RESILIENT, STRUCTURAL
        self.distinct_attack_axes: List[str] = []
        self.discovery_refusal_rate: float = 0.0

        # Agents Fleet
        self.agents: Dict[str, AgentRecord] = {}
        self.agent_counter = 0
        self.total_spawned = 0
        self.completed_tasks = 0
        self.failed_tasks = 0
        self.hydra_recoveries = 0

        # Epistemic Conscience & Hypotheses
        self.hypotheses: Dict[str, HypothesisRecord] = {}
        self.epistemic_events: deque = deque(maxlen=8)

        # Experimentation Cleanroom & Proof-of-Work
        self.experiments: Dict[str, ExperimentRecord] = {}
        self.pow_verifications = 0
        self.experiments_executed = 0

        # GNN Oracle & Knowledge Graph
        self.gnn = GNNOracleRecord()

        # Multi-Agent Tribunal & Falsification
        self.tribunal: Dict[str, TribunalRecord] = {}

        # Discovery & Grounding Metrics
        self.facts_harvested = 0
        self.entities_grounded = 0
        self.causal_edges = 0
        self.grounded_datasets: List[str] = []

        # Telemetry / Log buffer
        self.recent_logs: deque = deque(maxlen=20)
        self.is_completed = False
        self.completion_result: Optional[Dict[str, Any]] = None

    def get_elapsed_str(self) -> str:
        elapsed = time.time() - self.start_time
        hrs = int(elapsed // 3600)
        mins = int((elapsed % 3600) // 60)
        secs = int(elapsed % 60)
        return f"{hrs:02d}h {mins:02d}m {secs:02d}s"

    def get_remaining_str(self) -> str:
        total_secs = self.runtime_hours * 3600
        elapsed = time.time() - self.start_time
        remaining = max(0, total_secs - elapsed)
        rem_int = int(round(remaining))
        hrs = int(rem_int // 3600)
        mins = int((rem_int % 3600) // 60)
        return f"{hrs:02d}h {mins:02d}m"

    def get_cycle_progress_percent(self) -> float:
        """Percentage of research campaign cycles completed."""
        return min(100.0, (self.current_cycle / max(1, self.max_cycles)) * 100.0)

    def get_cycle_progress_bar_str(self, width: int = 30) -> str:
        """ASCII progress bar for research campaign."""
        pct = self.get_cycle_progress_percent() / 100.0
        filled = int(round(width * pct))
        empty = max(0, width - filled)
        return f"[{'█' * filled}{'░' * empty}]"


