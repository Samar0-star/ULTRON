class SandboxResult:
    def __init__(self, stdout: str, stderr: str, exit_code: int, duration: float, workdir: Optional[str] = None):
        self.stdout = stdout
        self.stderr = stderr
        self.exit_code = exit_code
        self.duration = duration
        self.workdir = workdir

    def to_dict(self) -> Dict[str, Any]:
        return {
            "stdout": self.stdout,
            "stderr": self.stderr,
            "exit_code": self.exit_code,
            "duration": self.duration,
            "success": self.exit_code == 0,
            "workdir": self.workdir
        }

class ASTValidator(ast.NodeVisitor):
    """
    Blocks usage of dangerous modules and functions via static analysis.
    """
    # [SCIENCE] Relaxed imports for scientific libraries (numpy, pandas often use these)
    DANGEROUS_IMPORTS = {
        "subprocess", "shutil", 
        "importlib", "builtins", "pty",
        "ctypes", "_ctypes", "cffi", "_cffi_backend",
        "posix", "_posixsubprocess", "resource"
    }
    
    # [BRUTAL] Block dangerous methods even if module is allowed
    DANGEROUS_FUNCTIONS = {
        "eval", "exec", "compile", "input",
        "breakpoint", "delattr",
        # OS/System specific dangerous calls
        "system", "popen", "spawn", "fork", "kill", "setuid", "setgid", 
        "chroot", "chmod", "chown", "remove", "rmdir", "rename",
        "execve", "execv", "execvp", "execl"
    }
    
    # [BRUTAL] Block dangerous attributes (e.g., sys.modules)
    # [SCIENCE] Allowed 'environ' for data path resolution
    # [GODZILLA FIX] Allowed stdout/stderr/version for benign diagnostics
    DANGEROUS_ATTRIBUTES = {
        "modules", "meta_path", "path_hooks", "argv", "__subclasses__",
        "execve", "execv", "execvp", "execl", "system", "popen", "spawn", "fork", "kill"
    }
    
    ALLOWED_SYS_ATTRIBUTES = {
        "stdout", "stderr", "version", "version_info", "executable", "platform", "exit"
    }

    ALLOWED_MAGIC_ATTRIBUTES = {
        "__name__", "__init__", "__main__", "__version__", "__file__",
        "__doc__", "__len__", "__iter__", "__enter__", "__exit__",
        "__call__", "__class__", "__repr__", "__str__", "__getitem__",
        "__setitem__", "__delitem__", "__contains__", "__eq__", "__ne__"
    }

    def __init__(self):
        self.errors = []
        self.aliases = {}

    def _resolve_name(self, node) -> str:
        """Resolve AST node to a module path string if possible."""
        if isinstance(node, ast.Name):
            return self.aliases.get(node.id, node.id)
        elif isinstance(node, ast.Attribute):
            val = self._resolve_name(node.value)
            if val:
                return f"{val}.{node.attr}"
        return ""

    def visit_Import(self, node):
        for alias in node.names:
             name = alias.name
             asname = alias.asname or name
             self.aliases[asname] = name
             if name.split('.')[0] in self.DANGEROUS_IMPORTS:
                  self.errors.append(f"Import of '{name}' is forbidden.")
        self.generic_visit(node)

    def visit_ImportFrom(self, node):
        module = node.module
        if module and module.split('.')[0] in self.DANGEROUS_IMPORTS:
            self.errors.append(f"Import from '{module}' is forbidden.")
        if module:
            mod_root = module.split('.')[0]
            for alias in node.names:
                name = alias.name
                asname = alias.asname or name
                self.aliases[asname] = f"{module}.{name}"
                if name in self.DANGEROUS_FUNCTIONS or (mod_root == "os" and name in {"remove", "unlink", "rmdir", "rename"}):
                    self.errors.append(f"Import of '{module}.{name}' is forbidden.")
        self.generic_visit(node)
    
    def visit_Name(self, node):
        resolved = self.aliases.get(node.id, node.id)
        if resolved in {"__builtins__"}:
            self.errors.append(f"Use of name '{node.id}' is forbidden.")
        self.generic_visit(node)

    def visit_Attribute(self, node):
        attr_name = node.attr
        # Allow benign sys attributes
        resolved_val = self._resolve_name(node.value)
        if resolved_val == "sys":
            if attr_name in self.ALLOWED_SYS_ATTRIBUTES:
                return # Skip dangerous check for these
            else:
                self.errors.append(f"Access to sys attribute '{attr_name}' is forbidden.")
                return
                
        if attr_name.startswith("__") and attr_name.endswith("__") and attr_name not in self.ALLOWED_MAGIC_ATTRIBUTES:
             self.errors.append(f"Access to magic attribute '{attr_name}' is forbidden.")
        if attr_name in self.DANGEROUS_ATTRIBUTES:
             self.errors.append(f"Access to attribute '{attr_name}' is forbidden.")
        self.generic_visit(node)

    def visit_Call(self, node):
        func_node = node.func
        if isinstance(func_node, ast.Subscript):
            # Check if subscript argument is a constant string that is a dangerous function
            if isinstance(getattr(func_node, 'slice', None), ast.Constant):
                val = func_node.slice.value
                if val in self.DANGEROUS_FUNCTIONS or val in {
                    "system", "popen", "spawn", "fork", "kill", "setuid", "setgid", 
                    "chroot", "chmod", "chown", "rmdir", "execve", "execv", "execvp", "execl"
                }:
                    self.errors.append(f"Call to '{val}' is forbidden.")
            func_node = func_node.value

        if isinstance(func_node, ast.Name):
            func_name = func_node.id
            resolved = self.aliases.get(func_name, func_name)
            if func_name in {"getattr", "setattr"} and len(node.args) >= 2:
                arg1 = node.args[1]
                if isinstance(arg1, ast.Constant) and isinstance(arg1.value, str):
                    attr_str = arg1.value
                    if (attr_str.startswith("__") and attr_str not in self.ALLOWED_MAGIC_ATTRIBUTES) or attr_str in self.DANGEROUS_ATTRIBUTES:
                        self.errors.append(f"Call to '{func_name}' with forbidden attribute '{attr_str}'.")
                elif func_name == "setattr":
                    self.errors.append("Call to 'setattr' with dynamic attribute name is forbidden.")
            if (func_name in self.DANGEROUS_FUNCTIONS or 
                resolved in self.DANGEROUS_FUNCTIONS or 
                resolved.split('.')[-1] in self.DANGEROUS_FUNCTIONS):
                self.errors.append(f"Call to '{func_name}' is forbidden.")
        elif isinstance(func_node, ast.Attribute):
            func_name = func_node.attr
            dangerous_attributes = {
                "system", "popen", "spawn", "fork", "kill", "setuid", "setgid", 
                "chroot", "chmod", "chown", "rmdir", "execve", "execv", "execvp", "execl"
            }
            module_path = self._resolve_name(func_node.value)
            if func_name in {"remove", "rename"}:
                # Only block remove/rename if accessed on 'os' module
                if module_path.split('.')[0] == "os":
                    self.errors.append(f"Call to 'os.{func_name}' is forbidden.")
            elif func_name in dangerous_attributes:
                self.errors.append(f"Call to method '{func_name}' is forbidden.")
        self.generic_visit(node)


class SandboxProvider(ABC):
    @abstractmethod
    def run(self, code: str, timeout: int = 300, profile: str = "general", extra_env: Optional[Dict[str, str]] = None) -> SandboxResult:
        pass

class RestrictedSubprocessProvider(SandboxProvider):
    NUCLEAR_PREAMBLE = """
import sys
import os
import builtins as _ultron_builtins

# [TITAN V72.6] Transparent Network Block & Filesystem Containment
def block_network(*args, **kwargs): raise RuntimeError("GodMode Sandbox: Network access forbidden.")

try:
    import socket
    socket.socket.connect = block_network
    socket.socket.bind = block_network
    socket.getaddrinfo = block_network
except Exception as e: print(f"[SANDBOX ESCAPE ATTEMPTED] Network block failed: {e}")

os.system = block_network
os.popen = block_network

_orig_open = _ultron_builtins.open
_allowed_write_root = os.path.realpath(os.getcwd())

def _guarded_open(file, mode='r', *args, **kwargs):
    if isinstance(mode, str) and any(m in mode for m in ('w', 'a', 'x', '+')):
        try:
            target_real = os.path.realpath(str(file))
            if not (target_real == _allowed_write_root or target_real.startswith(_allowed_write_root + os.sep)):
                raise PermissionError(f"GodMode Sandbox: Writing outside sandbox workdir is forbidden ({file})")
        except PermissionError:
            raise
        except Exception:
            pass
    return _orig_open(file, mode, *args, **kwargs)

_ultron_builtins.open = _guarded_open
"""

    def run(self, code: str, timeout: int = 300, profile: str = "general", extra_env: Optional[Dict[str, str]] = None) -> SandboxResult:
        # 1. Validation
        try:
            tree = ast.parse(code)
            validator = ASTValidator()
            validator.visit(tree)
            if validator.errors:
                return SandboxResult("", "; ".join(validator.errors), 1, 0.0)
        except SyntaxError as e:
            return SandboxResult("", f"SyntaxError: {e}", 1, 0.0)

        # 2. Preamble
        full_code = self.NUCLEAR_PREAMBLE + "\n" + code
        
        with tempfile.NamedTemporaryFile(suffix=".py", mode="w", delete=False) as tmp:
            tmp.write(full_code)
            tmp_path = tmp.name

        # 3. [ULTRON GPU CLUSTER UPGRADE] Strict Environment Whitelist with GPU Acceleration Support
        whitelist = {
            "PATH", "PYTHONPATH", "LANG", "LC_ALL", "LC_CTYPE", "HOME", "USER",
            # NVIDIA CUDA Acceleration
            "CUDA_VISIBLE_DEVICES", "NVIDIA_VISIBLE_DEVICES", "NVIDIA_DRIVER_CAPABILITIES",
            "LD_LIBRARY_PATH", "DYLD_LIBRARY_PATH", "TORCH_CUDA_ARCH_LIST", "CUDA_HOME",
            # AMD ROCm Acceleration
            "ROCM_VISIBLE_DEVICES", "HIP_VISIBLE_DEVICES",
            # Environments & Framework Caches
            "CONDA_PREFIX", "VIRTUAL_ENV", "HF_HOME", "TRANSFORMERS_CACHE",
            "TORCH_HOME", "MPLCONFIGDIR", "TMPDIR", "TEMP", "TMP"
        }
        env = {k: v for k, v in os.environ.items() if k in whitelist}
        
        if extra_env:
            # Strip keys containing sensitive credentials to prevent leaks
            clean_extra = {k: v for k, v in extra_env.items() if not any(x in k.upper() for x in ["KEY", "TOKEN", "PASSWORD", "SECRET"])}
            env.update(clean_extra)
        
        # Ensure PYTHONPATH does NOT include the project root working directory to prevent importing backend modules
        env["PYTHONPATH"] = env.get("PYTHONPATH", "")

        effective_timeout = int(os.environ.get("SANDBOX_TIMEOUT", str(timeout)))

        start_time = time.time()
        results_cwd = os.path.join(os.getcwd(), "results")
        os.makedirs(results_cwd, exist_ok=True)

        try:
            process = subprocess.Popen(
                [sys.executable, "-u", tmp_path],
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                text=True,
                env=env,
                cwd=results_cwd,
                preexec_fn=os.setsid # [RIGOR FIX] Process group isolation for clean kills
            )
            stdout, stderr = process.communicate(timeout=effective_timeout)
            exit_code = process.returncode
        except subprocess.TimeoutExpired:
            # [RIGOR FIX] Explicit SIGKILL to the entire process group
            os.killpg(os.getpgid(process.pid), signal.SIGKILL)
            stdout, stderr = "", f"Timeout after {effective_timeout}s"
            exit_code = 1
        except Exception as e:
            stdout, stderr = "", str(e)
            exit_code = 1
        finally:
            if os.path.exists(tmp_path):
                try:
                    import shutil
                    # Always save the last executed script for debugging/forensics
                    debug_path = os.path.join(results_cwd, "last_executed_script.py")
                    shutil.copy2(tmp_path, debug_path)
                    if exit_code != 0:
                        failed_path = os.path.join(results_cwd, "failed_script.py")
                        shutil.copy2(tmp_path, failed_path)
                except Exception as copy_err:
                    logger.warning(f" [SANDBOX] Failed to save debug script copies: {copy_err}")
                os.unlink(tmp_path)

        return SandboxResult(stdout, stderr, exit_code, time.time() - start_time, workdir=results_cwd)

class DockerProvider(SandboxProvider):
    def __init__(self, image: str = "python:3.9-slim", mem_limit: str = "256m", cpu_percent: float = 0.5):
        self.image = image
        self.mem_limit = mem_limit
        self.cpu_percent = cpu_percent
        self._client = None
        self.max_retries = 2

    def _get_client(self):
        if self._client is None:
            import docker
            self._client = docker.from_env()
        return self._client

    def run(self, code: str, timeout: int = 300, profile: str = "general", extra_env: Optional[Dict[str, str]] = None) -> SandboxResult:
        last_result = None
        current_code = code
        for attempt in range(self.max_retries):
            result = self._execute_once(current_code, timeout, profile, extra_env=extra_env)
            last_result = result
            if result.exit_code == 0: return result
        return last_result

    def _execute_once(self, code: str, timeout: int, profile: str = "general", extra_env: Optional[Dict[str, str]] = None) -> SandboxResult:
        try:
            client = self._get_client()
            container = client.containers.run(
                self.image,
                command=["python", "-c", code],
                detach=True,
                mem_limit=self.mem_limit,
                network_disabled=True,
                environment=extra_env,
                stdout=True,
                stderr=True,
                cap_drop=["ALL"],
                security_opt=["no-new-privileges"],
                pids_limit=50
            )
            start_time = time.time()
            try:
                wait_result = container.wait(timeout=timeout)
                exit_code = wait_result.get("StatusCode", -1)
                stdout = container.logs(stdout=True, stderr=False).decode("utf-8")
                stderr = container.logs(stdout=False, stderr=True).decode("utf-8")
            except Exception as e:
                container.kill()
                stderr, exit_code = str(e), 1
            finally:
                container.remove()
            return SandboxResult(stdout, stderr, exit_code, time.time() - start_time)
        except Exception as e:
            return SandboxResult("", str(e), 1, 0.0)

class GodModeSandbox:
    def __init__(self):
        self._provider = RestrictedSubprocessProvider() # Default to subprocess for stability in this session

    def run(self, code: str, timeout: int = 300, profile: str = "general", extra_env: Optional[Dict[str, str]] = None) -> SandboxResult:
        return self._provider.run(code, timeout, profile, extra_env=extra_env)
