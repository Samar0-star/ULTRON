"""
ULTRON Scientific Protocol Models
==================================
Pydantic models for the DiscoveryArtifact schema used by the Sovereign
experiment designer and related pipeline components.

These models are imported by:
  - backend/experiments/designer.py
  - backend/agents/experiment_agent.py
"""

from typing import Any, Dict, List, Optional, Union
from pydantic import BaseModel, Field, field_validator
import math
import re


def _parse_numeric_field(v: Any, default: float) -> float:
    if v is None:
        return default
    if isinstance(v, (int, float)):
        return float(v)
    if isinstance(v, str):
        matches = re.findall(r"[-+]?\d*\.?\d+(?:[eE][-+]?\d+)?", v)
        if matches:
            try:
                return float(matches[-1])
            except ValueError:
                pass
    return default


class StatisticalTest(BaseModel):
    test_type: str = Field(default="t_test", description="Type of statistical test (t_test, anova, chi_square, etc.)")
    expected_effect_size: float = Field(default=0.5, description="Cohen's d or equivalent effect size")
    required_power: float = Field(default=0.8, description="Statistical power (1 - beta)")
    alpha: float = Field(default=0.05, description="Type I error rate")
    groups: Optional[List[str]] = Field(default=None, description="Group names for ANOVA")
    sample_size: Optional[int] = Field(default=None, description="Calculated or required sample size")

    model_config = {"extra": "allow"}

    @field_validator("expected_effect_size", mode="before")
    @classmethod
    def _validate_effect_size(cls, v: Any) -> float:
        val = abs(_parse_numeric_field(v, 0.5))
        return val if val > 0 else 0.5

    @field_validator("required_power", mode="before")
    @classmethod
    def _validate_req_power(cls, v: Any) -> float:
        val = _parse_numeric_field(v, 0.8)
        if val > 1.0 and val <= 100.0:
            val = val / 100.0
        return max(0.50, min(0.9999, val))

    @field_validator("alpha", mode="before")
    @classmethod
    def _validate_alpha(cls, v: Any) -> float:
        val = _parse_numeric_field(v, 0.05)
        return max(1e-6, min(0.50, val))


class ExperimentalDesign(BaseModel):
    approach: Optional[str] = Field(default=None, description="Overall experimental approach")
    steps: Optional[List[Any]] = Field(default_factory=list, description="Step-by-step experimental procedure")
    controls: Optional[List[str]] = Field(default_factory=list, description="Control conditions")
    variables: Optional[Dict[str, Any]] = Field(default_factory=dict, description="Independent and dependent variables")
    datasets: Optional[List[str]] = Field(default_factory=list, description="Datasets to use")

    model_config = {"extra": "allow"}


class DiscoveryArtifact(BaseModel):
    """
    Core scientific discovery artifact schema.
    Generated by the Experiment Designer and validated before implementation.
    """
    # Required identifying fields
    title: str = Field(default="Unnamed Discovery Mission", description="Title of the discovery mission")
    hypothesis_id: Optional[str] = Field(default=None, description="Reference ID of the hypothesis being tested")
    hypothesis_statement: Optional[str] = Field(default=None, description="Full hypothesis text")

    # Domain & classification
    domain: str = Field(default="machine_learning", description="Scientific domain")
    research_type: Optional[str] = Field(default="experimental", description="Type: experimental, observational, theoretical")

    # Experimental configuration
    experimental_design: Optional[Union[ExperimentalDesign, Dict[str, Any]]] = Field(
        default_factory=dict, description="Full experimental design specification"
    )
    methodology: Optional[str] = Field(default=None, description="Methodology description")
    protocol: Optional[Union[str, Dict[str, Any], List[Any]]] = Field(
        default=None, description="Detailed experimental protocol"
    )

    # Statistical rigor
    statistical_tests: Optional[List[Union[StatisticalTest, Dict[str, Any]]]] = Field(
        default_factory=list, description="Statistical tests to be applied"
    )
    sample_size: Optional[int] = Field(default=None, description="Required sample size from power analysis")
    sample_size_rationale: Optional[str] = Field(default=None, description="Justification for sample size")
    confidence_level: Optional[float] = Field(default=0.95, description="Confidence level for intervals")
    power: Optional[float] = Field(default=0.80, description="Statistical power")

    # Expected outcomes
    expected_results: Optional[Union[str, Dict[str, Any], List[Any]]] = Field(
        default=None, description="Predicted experimental outcomes"
    )
    falsification_criteria: Optional[Union[str, List[str], Dict[str, Any]]] = Field(
        default=None, description="Criteria under which the hypothesis is falsified"
    )
    success_metrics: Optional[Union[str, List[str], Dict[str, Any]]] = Field(
        default=None, description="Metrics defining experimental success"
    )

    # Code specification
    implementation_notes: Optional[str] = Field(default=None, description="Notes for the code implementer")
    required_libraries: Optional[List[str]] = Field(default_factory=list, description="Python library dependencies")
    data_sources: Optional[Union[List[str], Dict[str, Any]]] = Field(
        default_factory=list, description="Real data files or datasets to use"
    )

    # Rigor scoring
    rigor_score: Optional[float] = Field(default=None, description="Computed methodological rigor score (0-1)")
    bootstrap_validation: Optional[Union[str, Dict[str, Any]]] = Field(
        default=None, description="Bootstrap resampling specification (auto-injected if missing)"
    )

    # Metadata
    version: Optional[str] = Field(default="1.0", description="Artifact schema version")
    tags: Optional[List[str]] = Field(default_factory=list, description="Classification tags")
    notes: Optional[str] = Field(default=None, description="Free-form additional notes")

    model_config = {"extra": "allow"}

    def calculate_rigor_score(self) -> float:
        """
        Compute a methodological rigor score (0.0 → 1.0).
        Checks both canonical and ExperimentDesigner (`extra="allow"`) fields.
        """
        extra = getattr(self, "__pydantic_extra__", None) or {}
        score = 0.0
        has_hypothesis = bool(
            self.hypothesis_statement
            or extra.get("hypothesis")
            or getattr(self, "hypothesis", None)
        )
        if has_hypothesis:
            score += 0.15
        if self.statistical_tests:
            score += 0.20

        effective_n = self.sample_size
        if not effective_n and self.statistical_tests:
            for st in self.statistical_tests:
                n_cand = st.get("sample_size") if isinstance(st, dict) else getattr(st, "sample_size", None)
                if isinstance(n_cand, (int, float)) and n_cand > 1:
                    effective_n = int(n_cand)
                    break
        if effective_n and effective_n > 1:
            score += 0.15

        has_falsification = bool(
            self.falsification_criteria
            or extra.get("falsification_plan")
            or getattr(self, "falsification_plan", None)
        )
        if has_falsification:
            score += 0.20

        steps = extra.get("steps") or getattr(self, "steps", None) or []
        controls = extra.get("control_groups") or getattr(self, "control_groups", None) or []
        variables = extra.get("variables") or getattr(self, "variables", None) or []
        has_design = bool(self.experimental_design or steps or controls or variables)
        if has_design:
            score += 0.15

        has_bootstrap = bool(self.bootstrap_validation)
        if not has_bootstrap and isinstance(steps, list):
            has_bootstrap = any(
                "bootstrap" in str(s.get("title", "") if isinstance(s, dict) else s).lower()
                or "bootstrap" in str(s.get("action", "") if isinstance(s, dict) else s).lower()
                for s in steps
            )
        if has_bootstrap:
            score += 0.10

        has_data = bool(
            self.data_sources
            or extra.get("datasets")
            or extra.get("dataset_uri")
            or variables
        )
        if has_data:
            score += 0.05

        self.rigor_score = round(score, 3)
        return self.rigor_score

    @field_validator("confidence_level", mode="before")
    @classmethod
    def validate_confidence(cls, v):
        val = _parse_numeric_field(v, 0.95)
        if val > 1.0 and val <= 100.0:
            val = val / 100.0
        return max(0.50, min(0.9999, val))

    @field_validator("power", mode="before")
    @classmethod
    def validate_power(cls, v):
        val = _parse_numeric_field(v, 0.80)
        if val > 1.0 and val <= 100.0:
            val = val / 100.0
        return max(0.50, min(0.9999, val))
